"""Multi-turn stateful agent pipeline benchmark: tests multi-iteration I/O and state persistence."""
from __future__ import annotations

from ...core.models import ExecuteCodeRequest


class AgentMultiturnBenchmark:
    name = "agent_multiturn"
    description = (
        "Simulates a 5-iteration stateful agent workflow: init state, ingest CSV, "
        "compute anomaly insights, generate decision report, and verify cross-turn filesystem integrity."
    )

    @staticmethod
    def get_request() -> ExecuteCodeRequest:
        code = (
            "import os, time, json, csv, hashlib\n"
            "work_dir = '.' if os.access('.', os.W_OK) else '/tmp'\n"
            "p_state = os.path.join(work_dir, 'agent_state.json')\n"
            "p_tx = os.path.join(work_dir, 'step2_transactions.csv')\n"
            "p_anom = os.path.join(work_dir, 'step3_anomalies.json')\n"
            "p_rep = os.path.join(work_dir, 'step4_decision_report.md')\n"
            "\n"
            "t_start = time.perf_counter()\n"
            "\n"
            "# --- TURN 1: Initialize Agent Session & Memory State ---\n"
            "t0 = time.perf_counter()\n"
            "state = {\n"
            "    'session_id': 'agent-sess-994',\n"
            "    'agent_model': 'bench-agent-v1',\n"
            "    'turns': [],\n"
            "    'scratchpad': 'Session initialized. Ready for transaction pipeline.'\n"
            "}\n"
            "state['turns'].append({'turn': 1, 'action': 'init_session', 'ts': time.time()})\n"
            "with open(p_state, 'w') as f:\n"
            "    json.dump(state, f, indent=2)\n"
            "t_turn1 = (time.perf_counter() - t0) * 1000\n"
            "\n"
            "# --- TURN 2: Ingest & Write Tabular Transaction Data (500 rows) ---\n"
            "t1 = time.perf_counter()\n"
            "with open(p_state, 'r') as f:\n"
            "    curr_state = json.load(f)\n"
            "rows = [\n"
            "    {'tx_id': f'tx_{i}', 'amount': (i * 17.5) % 1000, 'flag': (i % 23 == 0)}\n"
            "    for i in range(500)\n"
            "]\n"
            "with open(p_tx, 'w', newline='') as f:\n"
            "    writer = csv.DictWriter(f, fieldnames=['tx_id', 'amount', 'flag'])\n"
            "    writer.writeheader()\n"
            "    writer.writerows(rows)\n"
            "curr_state['turns'].append({'turn': 2, 'action': 'ingest_csv', 'count': len(rows)})\n"
            "with open(p_state, 'w') as f:\n"
            "    json.dump(curr_state, f, indent=2)\n"
            "t_turn2 = (time.perf_counter() - t1) * 1000\n"
            "\n"
            "# --- TURN 3: Read CSV, Filter Anomalies, Write Intermediate Insights ---\n"
            "t2 = time.perf_counter()\n"
            "with open(p_tx, 'r') as f:\n"
            "    reader = csv.DictReader(f)\n"
            "    anomalies = [r for r in reader if r['flag'] == 'True' and float(r['amount']) > 200.0]\n"
            "insights = {\n"
            "    'total_anomalies_detected': len(anomalies),\n"
            "    'sample_anomalies': anomalies[:5],\n"
            "    'requires_human_review': len(anomalies) > 5\n"
            "}\n"
            "with open(p_anom, 'w') as f:\n"
            "    json.dump(insights, f, indent=2)\n"
            "with open(p_state, 'r') as f:\n"
            "    curr_state = json.load(f)\n"
            "curr_state['turns'].append({'turn': 3, 'action': 'filter_anomalies', 'flagged': len(anomalies)})\n"
            "with open(p_state, 'w') as f:\n"
            "    json.dump(curr_state, f, indent=2)\n"
            "t_turn3 = (time.perf_counter() - t2) * 1000\n"
            "\n"
            "# --- TURN 4: Synthesize Decision Report Markdown ---\n"
            "t3 = time.perf_counter()\n"
            "with open(p_anom, 'r') as f:\n"
            "    insights_data = json.load(f)\n"
            "report_md = (\n"
            "    f'# Agent Executive Decision Report\\n\\n'\n"
            "    f'- **Session**: {curr_state[\"session_id\"]}\\n'\n"
            "    f'- **Anomalies Found**: {insights_data[\"total_anomalies_detected\"]}\\n'\n"
            "    f'- **Escalate**: {insights_data[\"requires_human_review\"]}\\n\\n'\n"
            "    f'## Recommendations\\nImmediate quarantine of flagged transaction tokens.'\n"
            ")\n"
            "with open(p_rep, 'w') as f:\n"
            "    f.write(report_md)\n"
            "curr_state['turns'].append({'turn': 4, 'action': 'generate_report', 'bytes': len(report_md)})\n"
            "with open(p_state, 'w') as f:\n"
            "    json.dump(curr_state, f, indent=2)\n"
            "t_turn4 = (time.perf_counter() - t3) * 1000\n"
            "\n"
            "# --- TURN 5: Multi-Turn Verification & State Continuity Check ---\n"
            "t4 = time.perf_counter()\n"
            "required_files = [p_state, p_tx, p_anom, p_rep]\n"
            "all_exist = all(os.path.exists(p) for p in required_files)\n"
            "with open(p_state, 'r') as f:\n"
            "    final_state = json.load(f)\n"
            "has_5_turns = len(final_state.get('turns', [])) == 4\n"
            "continuity_ok = all_exist and has_5_turns\n"
            "t_turn5 = (time.perf_counter() - t4) * 1000\n"
            "\n"
            "total_ms = (time.perf_counter() - t_start) * 1000\n"
            "\n"
            "print('MULTITURN_ITERATIONS:5')\n"
            "print(f'TURN_1_INIT_MS:{t_turn1:.2f}')\n"
            "print(f'TURN_2_INGEST_MS:{t_turn2:.2f}')\n"
            "print(f'TURN_3_ANALYSIS_MS:{t_turn3:.2f}')\n"
            "print(f'TURN_4_DECISION_MS:{t_turn4:.2f}')\n"
            "print(f'TURN_5_VERIFY_MS:{t_turn5:.2f}')\n"
            "print(f'TOTAL_MULTITURN_MS:{total_ms:.2f}')\n"
            "print(f'STATE_CONTINUITY_SUCCESS:{continuity_ok}')\n"
        )
        return ExecuteCodeRequest(code=code, timeout_seconds=90)
